export async function syncAllToFirestore() {
  console.log("Connecting directly to Firestore database:", config.firestoreDatabaseId);

  // 1. Fetch remote merchants from backend bot to merge
  let remoteMerchants: any[] = [];
  try {
    const res = await fetch("https://floate-bot.onrender.com/api/admin/merchants", {
      headers: { "x-api-key": "floate_live_sk_7f8a92b3c4e5d6" }
    });
    if (res.ok) {
      const data = await res.json();
      remoteMerchants = data.merchants || [];
      console.log(`Fetched ${remoteMerchants.length} merchants from live Floate Bot`);
    }
  } catch (e) {
    console.warn("Notice: could not fetch remote bot merchants, using curated catalogue:", e);
  }

  // Deduplicate and prepare merchants
  const merchantMap = new Map<string, any>();

  // Add curated merchants first
  CURATED_MERCHANTS.forEach(m => {
    merchantMap.set(m.slug, m);
  });

  // Add remote merchants
  remoteMerchants.forEach(rm => {
    const bName = rm.businessName?.trim();
    if (!bName) return;
    const slug = bName.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
    if (!merchantMap.has(slug)) {
      const city = rm.location?.split(",")[0]?.trim() || "Commercial Hub";
      const state = rm.location?.split(",")[1]?.trim() || "Nigeria";
      const hub = rm.geoHubName || `${city} Market Hub`;
      const cat = rm.category || "Commercial Merchandise";
      
      merchantMap.set(slug, {
        id: rm.id || slug,
        slug,
        name: bName,
        businessName: bName,
        handle: `@${slug}`,
        category: cat,
        primaryCategory: cat,
        city,
        state,
        market: hub,
        location: `${city}, ${state}`,
        marketLocation: `${hub}, ${city}, ${state}`,
        marketShort: hub,
        geoHubName: hub,
        whatsapp: rm.id?.startsWith("+") ? rm.id : (rm.whatsapp || "+2348031234567"),
        whatsappNumber: rm.id?.replace(/[^0-9]/g, "") || "2348031234567",
        verified: Boolean(rm.isVerified || rm.verifiedStatus === "YES"),
        isVerified: Boolean(rm.isVerified || rm.verifiedStatus === "YES"),
        status: "active",
        rating: 4.95,
        completedEscrows: rm.totalSafePaySales || 850,
        safePayLevel: "Verified Merchant",
        activeStatus: "Active on WhatsApp now",
        bio: `${cat} verified merchant with direct delivery and store pickup in ${city}.`,
        description: `${cat} verified merchant with direct delivery and store pickup in ${city}.`,
        avatarUrl: rm.avatarUrl || "https://images.unsplash.com/photo-1472099645785-5658abf4ff4e?auto=format&fit=crop&w=400&q=80",
        product: ""
      });
    }
  });

  console.log(`Writing ${merchantMap.size} merchants to Firestore 'businesses' collection...`);
  for (const [slug, mData] of merchantMap.entries()) {
    try {
      await setDoc(doc(db, "businesses", slug), mData, { merge: true });
    } catch (err: any) {
      console.warn(`Error writing merchant ${slug}:`, err.message);
    }
  }

  console.log(`Writing ${CURATED_PRODUCTS.length} products to Firestore 'products' collection...`);
  for (const p of CURATED_PRODUCTS) {
    try {
      await setDoc(doc(db, "products", p.id), p, { merge: true });
    } catch (err: any) {
      console.warn(`Error writing product ${p.id}:`, err.message);
    }
  }

  const bSnap = await getDocs(collection(db, "businesses"));
  const pSnap = await getDocs(collection(db, "products"));
  console.log(`Firestore Sync Complete! Database now contains:`);
  console.log(` - ${bSnap.size} businesses in 'businesses' collection`);
  console.log(` - ${pSnap.size} products in 'products' collection`);
}

// Execute if run directly
syncAllToFirestore()
  .then(() => {
    console.log("Seeding finished successfully.");
    process.exit(0);
  })
  .catch((err) => {
    console.error("Seeding failed:", err);
    process.exit(1);
  });
